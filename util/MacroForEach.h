#pragma once
#include "MsvcZcPreprocessor.h"
#include "MacroIdentity.h"
#include "MacroDeparen.h"
#include "MacroExpand.h"
#include "MacroParen.h"
//https://www.scs.stanford.edu/~dm/blog/va-opt.html
#define FOR_EACH(F, ...) __VA_OPT__(EXPAND(FOR_EACH_HELPER(F, __VA_ARGS__)))
#define FOR_EACH_HELPER(F, arg0, ...) F(arg0) __VA_OPT__(FOR_EACH_AGAIN PARENS (F, __VA_ARGS__))
#define FOR_EACH_AGAIN() FOR_EACH_HELPER

#define FOR_EACH_EX(F, x, ...) __VA_OPT__(EXPAND(FOR_EACH_EX_HELPER(F, x, __VA_ARGS__)))
#define FOR_EACH_EX_HELPER(F, x, arg0, ...) F(x, arg0) __VA_OPT__(FOR_EACH_EX_AGAIN PARENS (F, x, __VA_ARGS__))
#define FOR_EACH_EX_AGAIN() FOR_EACH_EX_HELPER

#define FOR_EACH_OP(F,OP, ...) __VA_OPT__(EXPAND(FOR_EACH_OP_HELPER(F,OP, __VA_ARGS__)))
#define FOR_EACH_OP_HELPER(F,OP, arg0, ...) F(arg0) __VA_OPT__(OP FOR_EACH_OP_AGAIN PARENS (F,OP, __VA_ARGS__))
#define FOR_EACH_OP_AGAIN() FOR_EACH_OP_HELPER

#define FOR_EACH_COMMA(F, ...) __VA_OPT__(EXPAND(FOR_EACH_COMMA_HELPER(F, __VA_ARGS__)))
#define FOR_EACH_COMMA_HELPER(F, arg0, ...) F(arg0) __VA_OPT__(, FOR_EACH_COMMA_AGAIN PARENS (F, __VA_ARGS__))
#define FOR_EACH_COMMA_AGAIN() FOR_EACH_COMMA_HELPER

#define FOR_EACH_COMMA_EX(F, x,...) __VA_OPT__(EXPAND(FOR_EACH_COMMA_EX_HELPER(F,x, __VA_ARGS__)))
#define FOR_EACH_COMMA_EX_HELPER(F, x, arg0, ...) F(x, arg0) __VA_OPT__(, FOR_EACH_COMMA_EX_AGAIN PARENS (F, x, __VA_ARGS__))
#define FOR_EACH_COMMA_EX_AGAIN() FOR_EACH_COMMA_EX_HELPER

#define FOR_EACH_TUPLE(F, ...) __VA_OPT__(EXPAND(FOR_EACH_TUPLE_HELPER(F, __VA_ARGS__)))
#define FOR_EACH_TUPLE_HELPER(F, arg0, ...) F arg0 __VA_OPT__(FOR_EACH_TUPLE_AGAIN PARENS (F, __VA_ARGS__))
#define FOR_EACH_TUPLE_AGAIN() FOR_EACH_TUPLE_HELPER

#define FOR_EACH_TUPLE_COMMA(F, ...) __VA_OPT__(EXPAND(FOR_EACH_TUPLE_COMMA_HELPER(F, __VA_ARGS__)))
#define FOR_EACH_TUPLE_COMMA_HELPER(F, arg0, ...) F arg0 __VA_OPT__(,FOR_EACH_TUPLE_COMMA_AGAIN PARENS (F, __VA_ARGS__))
#define FOR_EACH_TUPLE_COMMA_AGAIN() FOR_EACH_TUPLE_COMMA_HELPER

#define FOR_EACH_TUPLE_EX(F, x, ...) __VA_OPT__(EXPAND(FOR_EACH_TUPLE_EX_HELPER(F, x, __VA_ARGS__)))
#define FOR_EACH_TUPLE_EX_HELPER(F, x, arg0, ...) F LPAREN x, IDENTITY arg0 RPAREN __VA_OPT__(FOR_EACH_TUPLE_EX_AGAIN PARENS (F, x, __VA_ARGS__))
#define FOR_EACH_TUPLE_EX_AGAIN() FOR_EACH_TUPLE_EX_HELPER

#define FOR_EACH_TUPLE_COMMA_EX(F, x, ...) __VA_OPT__(EXPAND(FOR_EACH_TUPLE_COMMA_EX_HELPER(F, x, __VA_ARGS__)))
#define FOR_EACH_TUPLE_COMMA_EX_HELPER(F, x, arg0, ...) F LPAREN x, IDENTITY arg0 RPAREN __VA_OPT__(,FOR_EACH_TUPLE_COMMA_EX_AGAIN PARENS (F, x, __VA_ARGS__))
#define FOR_EACH_TUPLE_COMMA_EX_AGAIN() FOR_EACH_TUPLE_COMMA_EX_HELPER

#define FOR_EACH_DEPAREN(F, ...) __VA_OPT__(EXPAND(FOR_EACH_DEPAREN_HELPER(F, __VA_ARGS__)))
#define FOR_EACH_DEPAREN_HELPER(F, arg0, ...) F LPAREN DEPAREN2(arg0) RPAREN __VA_OPT__(FOR_EACH_DEPAREN_AGAIN PARENS (F, __VA_ARGS__))
#define FOR_EACH_DEPAREN_AGAIN() FOR_EACH_DEPAREN_HELPER

#define FOR_EACH_DEPAREN_EX(F, x, ...) __VA_OPT__(EXPAND(FOR_EACH_DEPAREN_EX_HELPER(F, x, __VA_ARGS__)))
#define FOR_EACH_DEPAREN_EX_HELPER(F, x, arg0, ...) F LPAREN x, DEPAREN2(arg0) RPAREN __VA_OPT__(FOR_EACH_DEPAREN_EX_AGAIN PARENS (F, x, __VA_ARGS__))
#define FOR_EACH_DEPAREN_EX_AGAIN() FOR_EACH_DEPAREN_EX_HELPER

#define FOR_EACH_DEPAREN_COMMA(F, ...) __VA_OPT__(EXPAND(FOR_EACH_DEPAREN_COMMA_HELPER(F, __VA_ARGS__)))
#define FOR_EACH_DEPAREN_COMMA_HELPER(F, arg0, ...) F LPAREN DEPAREN2(arg0) RPAREN __VA_OPT__(,FOR_EACH_DEPAREN_COMMA_AGAIN PARENS (F, __VA_ARGS__))
#define FOR_EACH_DEPAREN_COMMA_AGAIN() FOR_EACH_DEPAREN_COMMA_HELPER

#define FOR_EACH_DEPAREN_COMMA_EX(F, x, ...) __VA_OPT__(EXPAND(FOR_EACH_DEPAREN_COMMA_EX_HELPER(F, x, __VA_ARGS__)))
#define FOR_EACH_DEPAREN_COMMA_EX_HELPER(F, x, arg0, ...) F LPAREN x, DEPAREN2(arg0) RPAREN __VA_OPT__(,FOR_EACH_DEPAREN_COMMA_EX_AGAIN PARENS (F, x, __VA_ARGS__))
#define FOR_EACH_DEPAREN_COMMA_EX_AGAIN() FOR_EACH_DEPAREN_COMMA_EX_HELPER